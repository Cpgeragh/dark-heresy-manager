import { SkillSource } from "../../types/SkillSource";

// ─── Types ───────────────────────────────────────────────────────────────────

export interface GrenadeRef {
  id: string;
  name: string;
  source: string;
  /** Distinguishes grenades, mines and launcher-only missiles; defaults to "Grenade" if omitted. */
  type?: "Grenade" | "Mine" | "Missile";
  class: string;
  /** Damage string, "—" if no damage, or "Special" */
  damage: string;
  /** Penetration, "—" if not applicable */
  pen: string;
  /** Special rules string, "—" if none */
  specialRules: string;
  weight: string;
  value: string;
  availability: string;
  /** Full rules text for info modal */
  description?: string;
}

export interface RangedWeaponRef {
  id: string;
  name: string;
  source: SkillSource;
  class: string;
  range: string;
  rof: string;
  damage: string;
  pen: number | string;
  clip: number | string;
  reload: string;
  specialRules: string;
  weight: string;
  value: string;
  availability: string;
  /** Default ammo type label shown on the weapon card. Omit for integrated/no-ammo weapons. */
  ammoType?: string;
  /** AmmoRef IDs compatible with this weapon — drives the ammo picker dropdown. */
  compatibleAmmoIds?: string[];
  /** clip = spare clips/packs plus partial rounds; loose = individual rounds only. */
  ammoTracking?: "clip" | "loose";
  /** True for thrown weapons where the item itself is the projectile (bolas, throwing stars). Shows a quantity counter instead of ammo entries. */
  isThrown?: boolean;
  /** Prose description / special rules note shown in the info modal. */
  description?: string;
  /** Alternate firing profiles built into the weapon. */
  alternateProfiles?: Array<{
    label: string;
    range: string;
    rof: string;
    damage: string;
    pen: number | string;
    clip: number | string;
    reload: string;
    specialRules: string;
    ammoType?: string;
  }>;
  /** Melee profiles built into an otherwise ranged weapon. */
  alternateMeleeProfiles?: Array<{
    label: string;
    damage: string;
    pen: number | string;
    specialRules: string;
    twoHanded?: boolean;
  }>;
  /** Number of separately selectable internal magazines in the primary firing profile. */
  magazineSlots?: number;
}

export interface MeleeWeaponRef {
  id: string;
  name: string;
  source: SkillSource;
  class: string;
  damage: string;
  pen: number | string;
  specialRules: string;
  /** Multiplier applied to the wielder's Strength Bonus when calculating total Damage. */
  strengthBonusMultiplier?: number;
  twoHanded?: boolean;
  /** Fixed range for melee weapons that can also be thrown. */
  thrownRange?: string;
  weight: string;
  value: string;
  availability: string;
  /** Prose description / special rules note shown in the info modal. */
  description?: string;
  /** A one-piece firearm built into an otherwise melee weapon. */
  alternateRangedProfile?: {
    label: string;
    range: string;
    rof: string;
    damage: string;
    pen: number | string;
    clip: number | string;
    reload: string;
    specialRules: string;
    ammoType: string;
    compatibleAmmoIds: string[];
  };
  /** Alternate melee profiles built into this weapon. */
  alternateMeleeProfiles?: Array<{
    label: string;
    damage: string;
    pen: number | string;
    specialRules: string;
    twoHanded?: boolean;
  }>;
  /** Label for the weapon's default melee profile when it has alternates. */
  primaryMeleeProfileLabel?: string;
}

